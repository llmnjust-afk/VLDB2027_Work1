#!/usr/bin/env python3
"""Audit the completed adaptive experiment and regenerate the main results table."""

import argparse
from pathlib import Path

from compare_replay import digest
from revision_experiments import BUILD, ROOT, load_json
from run_adaptive_comparison import (
    FLAGS, METHODS, POLICY, STATIC_INTERVAL, TIMING_SCOPE, holdout_cases, run_case,
)


METHOD_ORDER = ("static", "static-net", "full", "full-fused", "adaptive")
GROUPS = (
    ("Generated updates", (
        ("email", "Email (generated)"),
        ("wikivote", "WikiVote"),
        ("amazon", "Amazon"),
    )),
    ("Transition-count batches, 7-day retention", (
        ("email-temporal", "Email (interactions)"),
        ("askubuntu", "Ask Ubuntu"),
    )),
    ("Shared 112-day replay, 7-day retention", (
        ("stackoverflow-b1d", "Stack Overflow (daily)"),
        ("stackoverflow-b14d", "Stack Overflow (14 days)"),
    )),
)


def audit(results):
    plan = load_json(results / "protocol.json")
    expected = {
        "flags": list(FLAGS),
        "methods": list(METHODS),
        "policy": POLICY,
        "static_interval": STATIC_INTERVAL,
        "threads": 1,
        "timer_scope": TIMING_SCOPE,
        "timing_replays": 3,
        "smoke_only": False,
        "prefix_batches": None,
    }
    machine = plan["machine"]
    if (any(plan[key] != value for key, value in expected.items())
            or "QEMU" not in machine["cpu_model"] or plan["cpu"] not in machine["affinity"]):
        raise ValueError("expected the matched, single-core full-replay protocol")
    required = {key for _, workloads in GROUPS for key, _ in workloads}
    cases = {case["dataset"]: case for case in plan["cases"]}
    if set(cases) != required or len(plan["cases"]) != len(required):
        raise ValueError("expected the five full streams and two holdout cadences")
    for holdout in holdout_cases():
        if cases[holdout["dataset"]] != holdout:
            raise ValueError("Stack Overflow cadence does not match its verified holdout stream")
    if any(cases[key]["scope"] != "full" for _, workloads in GROUPS[:2] for key, _ in workloads):
        raise ValueError("expected complete generated and transition-count streams")
    binary = results / "build/batchtruss"
    if digest(binary) != plan["binary_sha256"]:
        raise ValueError("executable differs from the recorded protocol")
    return {
        dataset: {row["method"]: row for row in run_case(
            results, cases[dataset], plan["timing_replays"], binary, {}, audit_only=True)}
        for _, workloads in GROUPS for dataset, _ in workloads
    }


def table_row(label, rows):
    first = rows["full"]
    cells = [label, f"{first['batches']:,}", f"{first['operations']:,}",
             f"{first['regional_mean_coverage']:.2%}".replace("%", r"\%")]
    means = [rows[method]["mean_ms_per_batch"] for method in METHOD_ORDER]
    best = min(means)
    for value in means:
        number = f"{value:.3f}"
        cells.append(rf"\textbf{{{number}}}" if value == best else number)
    return " & ".join(cells) + r" \\"


def render(workloads):
    lines = [
        "% Generated by scripts/generate_adaptive_paper.py",
        "% Source: .build/vldb2027-adaptive raw verification and timing CSVs",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Mean latency (ms/batch) across seven configurations. All methods use the",
        r"same native build and one pinned core of a QEMU VM. Each mean pools three",
        r"complete timing replays.",
        r"Coverage is the mean fraction of batch-end edges in the Regional closure.",
        r"Bold marks the lowest mean latency in each row.}",
        r"\label{tab:main-results}",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrrrr@{}}",
        r"\toprule",
        r" & & & & \multicolumn{2}{c}{Full-graph peeling} & \multicolumn{3}{c}{Regional and hybrid} \\",
        r"\cmidrule(lr){5-6}\cmidrule(l){7-9}",
        r"Workload & Batches & Raw events & Coverage & Static & Static-Net & Regional & Fused & Adaptive \\",
    ]
    for heading, members in GROUPS:
        lines.extend((r"\midrule", rf"\multicolumn{{9}}{{@{{}}l}}{{\emph{{{heading}}}}} \\"))
        lines.extend(table_row(label, workloads[key]) for key, label in members)
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular*}", r"\end{table*}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=BUILD / "vldb2027-adaptive")
    parser.add_argument("--paper", type=Path, default=ROOT / "VLDB2027_Work1-main/paper")
    args = parser.parse_args()
    table = render(audit(args.results))
    target = args.paper / "tables" / "tab_main_results.tex"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(table)
    print(f"Wrote {target}")


if __name__ == "__main__":
    main()
