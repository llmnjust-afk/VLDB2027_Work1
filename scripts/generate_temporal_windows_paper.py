#!/usr/bin/env python3
"""Audit the fixed-calendar Ask Ubuntu replays and regenerate the paper table."""

import argparse
from math import isfinite
from pathlib import Path
from statistics import mean, median

from compare_replay import csv_rows
from experiment_replays import audit_paired_case
from revision_experiments import ROOT, load_json
from revision_report import write_csv
from run_temporal_windows import DAY, END, METHODS, START, WINDOWS, experiment_case, prepare, summarize


def paper_rows(run):
    plan = load_json(run / "protocol.json")
    expected = {
        "dataset": "Ask Ubuntu", "start_utc": START, "end_utc": END,
        "step_seconds": DAY, "window_days": list(WINDOWS), "timing_replays": 3,
        "threads": 1, "methods": list(METHODS), "test_mode": False,
    }
    if any(plan.get(key) != value for key, value in expected.items()):
        raise ValueError(f"{run}: expected the complete 2015 daily experiment")
    prepared = prepare(run, None, END, plan)

    for days in WINDOWS:
        case, checkpoints, traces = experiment_case(prepared, days, END)
        directory = run / case["dataset"]
        runs = plan["timing_replays"]
        audit_paired_case(directory, case, METHODS, runs, expected_traces=traces)
        rows = summarize(directory, case, checkpoints, runs)

        region_by_replay = []
        daily_medians = {}
        for method in METHODS:
            trials = [csv_rows(directory / f"{method}.timing.{i}.batches.csv") for i in range(runs)]
            daily_medians[method] = [
                median(float(replay["elapsed_us"]) / 1000 for replay in day)
                for day in zip(*trials, strict=True)
            ]
            if method == "full":
                region_by_replay = [
                    [int(batch["region_edges"]) for batch in replay] for replay in trials
                ]

        regions = region_by_replay[0]
        edges = [int(row["active_edges"]) for row in checkpoints]
        if (any(regions != replay for replay in region_by_replay[1:])
                or any(not 0 <= r <= e for r, e in zip(regions, edges, strict=True))):
            raise ValueError(f"{directory}: invalid or inconsistent Full closure size")
        coverage = mean(r / e if e else 0 for r, e in zip(regions, edges, strict=True))
        for row in rows:
            method = row["method"]
            summaries = [directory / f"{method}.timing.{i}.runs.csv" for i in range(runs)]
            recorded = [csv_rows(path) for path in summaries]
            if any(len(records) != 1 for records in recorded):
                raise ValueError(f"{directory}: expected one process summary per timing replay")
            builds = [float(records[0]["build_s"]) for records in recorded]
            rss = [int(records[0]["rss_mb"]) for records in recorded]
            if any(not isfinite(seconds) or seconds < 0 for seconds in builds) or min(rss) <= 0:
                raise ValueError(f"{directory}: invalid construction time or peak RSS")
            fastest_days = sum(
                all(daily_medians[method][i] < daily_medians[other][i]
                    for other in METHODS if method != other)
                for i in range(len(checkpoints))
            )
            yield dict(row, mean_full_region_edges=mean(regions), mean_full_coverage=coverage,
                       fastest_days=fastest_days, mean_construction_ms=1e3 * mean(builds),
                       peak_rss_mib_min=min(rss), peak_rss_mib_max=max(rss),
                       timing_run_summaries="|".join(str(path.resolve()) for path in summaries),
                       source=str(directory.resolve()),
                       checkpoints=str((prepared / f"w{days}d" / "checkpoints.csv").resolve()))


def table(rows):
    lines = [
        "% Generated by scripts/generate_temporal_windows_paper.py",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Ask Ubuntu in 2015 with 365 common UTC day-end checkpoints and three",
        r"single-thread timing replays per window. Graph and closure sizes are",
        r"checkpoint means. Coverage is the mean fraction of active edges in",
        r"Regional's closure. Latency is in ms per daily batch. P95 pools 1,095",
        r"observations per method and window. Bold marks the lowest mean.}",
        r"\label{tab:temporal-windows}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrrrrrrr@{}}",
        r"\toprule",
        r"& & \multicolumn{2}{c}{Active graph} & \multicolumn{2}{c}{Regional closure}",
        r"& \multicolumn{2}{c}{Regional} & \multicolumn{2}{c}{Static} & \multicolumn{2}{c}{Resident Star} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}\cmidrule(lr){11-12}",
        r"Days & Raw events & Edges & Triangles & Edges & Coverage & Mean & P95 & Mean & P95 & Mean & P95 \\",
        r"\midrule",
    ]
    for days in WINDOWS:
        group = [row for row in rows if row["window_days"] == days]
        workload = group[0]
        first = [
            str(days), f"{workload['operations']:,}", f"{workload['mean_active_edges']:,.0f}",
            f"{workload['mean_active_triangles']:,.0f}", f"{workload['mean_full_region_edges']:,.0f}",
            f"{100 * workload['mean_full_coverage']:.1f}" + r"\%",
        ]
        latencies = []
        best = min(row["mean_ms_per_batch"] for row in group)
        for row in group:
            value = f"{row['mean_ms_per_batch']:.3f}"
            if row["mean_ms_per_batch"] == best:
                value = rf"\textbf{{{value}}}"
            latencies.extend((value, f"{row['pooled_p95_ms']:.3f}"))
        lines.append(" & ".join(first + latencies) + r" \\")
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular*}", r"\end{table*}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, default=ROOT / ".build/vldb2027-temporal-windows")
    parser.add_argument("--paper", type=Path, default=ROOT / "VLDB2027_Work1-main/paper")
    args = parser.parse_args()
    rows = list(paper_rows(args.run))
    tables = args.paper / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    write_csv(tables / "temporal_window_results.csv", rows)
    (tables / "tab_temporal_windows.tex").write_text(table(rows))
    print(f"Verified and exported {len(rows)} window/method rows to {tables}")


if __name__ == "__main__":
    main()
