#!/usr/bin/env python3
"""Audit the matched-thread replays and regenerate the paper table and CSV."""

import argparse
from pathlib import Path
from statistics import median

from compare_replay import csv_rows
from experiment_replays import audit_paired_case
from revision_experiments import LATENCY_CLOCK, LATENCY_SCOPE, ROOT, load_json
from revision_report import LABELS, write_csv
from run_matched_threads import DATASETS, METHODS, THREADS, summarize, verify_plan


def median_wins(directory, replays):
    medians_by_method = []
    for method in METHODS:
        trials = [csv_rows(directory / f"{method}.timing.{trial}.batches.csv")
                  for trial in range(replays)]
        medians_by_method.append([median(float(row["elapsed_us"]) for row in checkpoint)
                                  for checkpoint in zip(*trials, strict=True)])
    wins = dict.fromkeys(METHODS, 0)
    for matched in zip(*medians_by_method, strict=True):
        fastest = min(matched)
        if matched.count(fastest) == 1:
            wins[METHODS[matched.index(fastest)]] += 1
    return wins


def paper_rows(run):
    plan = load_json(run / "protocol.json")
    if (plan["test_mode"] or plan["timing_replays"] != 3 or not plan["separate_timing_processes"]
            or (plan["clock"], plan["timer_scope"]) != (LATENCY_CLOCK, LATENCY_SCOPE)):
        raise ValueError(f"{run}: expected the complete matched-thread protocol")
    verify_plan(run, plan)

    machine = plan["machine"]
    build = load_json(run / "build-manifest.json")
    if any(build[field] != machine[field] for field in ("host", "cpu_model", "platform")):
        raise ValueError(f"{run}: runtime and build machine records disagree")

    rows = []
    reference_traces = {}
    for name, case in plan["cases"].items():
        directory = run / name
        replays = plan["timing_replays"]
        dataset = case["dataset"]
        traces = audit_paired_case(directory, case, METHODS, replays)
        if traces != reference_traces.setdefault(dataset, traces):
            raise ValueError(f"{directory}: verified update trace differs across thread budgets")
        wins = median_wins(directory, replays)
        for row in summarize(directory, case, replays):
            rows.append(dict(row, strict_lowest_median_batches=wins[row["method"]],
                             host=machine["host"], cpu_model=machine["cpu_model"],
                             cpu_affinity=" ".join(str(cpu) for cpu in plan["affinity"]),
                             graph_sha256=case["graph_sha256"], stream_sha256=case["stream_sha256"],
                             binary_sha256=plan["binary_sha256"], source=str(directory)))

    single_thread = {(row["dataset"], row["method"]): row["mean_ms_per_batch"]
                     for row in rows if row["threads"] == 1}
    for row in rows:
        row["speedup_vs_one_thread"] = single_thread[row["dataset"], row["method"]] / row["mean_ms_per_batch"]
    return rows


def table(rows):
    indexed = {(row["dataset"], row["threads"], row["method"]): row for row in rows}
    lines = [
        "% Generated by scripts/generate_matched_threads_paper.py",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Batch latency under matched thread budgets in ms per batch.",
        r"Each configuration uses the same 200 batches per dataset and three",
        r"fresh-process timing replays. P95 pools 600 measurements per method",
        r"and configuration. Bold marks the lowest mean in each row.}",
        r"\label{tab:matched-threads}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrrr@{}}",
        r"\toprule",
        r"& & \multicolumn{2}{c}{Regional} & \multicolumn{2}{c}{Static} & \multicolumn{2}{c}{MSP} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
        r"Dataset & Threads & Mean & P95 & Mean & P95 & Mean & P95 \\",
        r"\midrule",
    ]
    for index, dataset in enumerate(DATASETS):
        if index:
            lines.append(r"\midrule")
        for threads in THREADS:
            cells = [LABELS[dataset] if threads == THREADS[0] else "", str(threads)]
            group = [indexed[dataset, threads, method] for method in METHODS]
            best = min(row["mean_ms_per_batch"] for row in group)
            for row in group:
                value = f"{row['mean_ms_per_batch']:.2f}"
                if row["mean_ms_per_batch"] == best:
                    value = rf"\textbf{{{value}}}"
                cells.extend((value, f"{row['pooled_p95_ms']:.2f}"))
            lines.append(" & ".join(cells) + r" \\")
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular*}", r"\end{table*}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, default=ROOT / ".build/vldb2027-matched-threads")
    parser.add_argument("--paper", type=Path, default=ROOT / "VLDB2027_Work1-main/paper")
    args = parser.parse_args()
    rows = paper_rows(args.run.resolve(strict=True))
    tables = args.paper / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    write_csv(tables / "matched_thread_results.csv", rows)
    (tables / "tab_matched_threads.tex").write_text(table(rows))
    print(f"Verified and exported {len(rows)} matched-thread rows to {tables}")


if __name__ == "__main__":
    main()
