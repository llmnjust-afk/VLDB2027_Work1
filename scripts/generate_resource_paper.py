#!/usr/bin/env python3
"""Report construction, cumulative latency, and process RSS from matched resident replays."""

import argparse
from itertools import accumulate
from math import isfinite
from pathlib import Path
from statistics import mean

from compare_replay import csv_rows
from compare_star_resident import METHODS, SCOPE, read_case
from revision_experiments import GENERATED, ROOT, load_json
from revision_report import LABELS, write_csv


def resource_rows(run):
    plan = load_json(run / "protocol.json")
    cases = {case["dataset"]: case for case in plan["cases"]}
    if (plan["test_mode"] or plan["threads"] != 1 or plan["replays"] != 3
            or plan["timer_scope"] != SCOPE or len(plan["cases"]) != len(GENERATED)
            or set(cases) != set(GENERATED)):
        raise ValueError("expected the matched, one-thread resident benchmark")

    rows = []
    for dataset in GENERATED:
        case = cases[dataset]
        directory = run / dataset
        complete = load_json(directory / "complete.json")
        if (case["scope"] != "full" or case["batch_operations"] != [1000] * 200
                or complete["case"] != case or complete["replays"] != plan["replays"]):
            raise ValueError(f"{directory}: expected a completed full generated stream")
        read_case(directory, case, plan["replays"])
        for method in METHODS:
            for replay in range(plan["replays"]):
                path = directory / f"{method}.timing.{replay}.runs.csv"
                argv = load_json(path.with_suffix(".argv.json"))
                row, = csv_rows(path)
                expected = ("batch", "full") if method == "full" else ("star-resident", "-")
                build_s = float(row["build_s"])
                rss_mib = int(row["rss_mb"])
                if (row["dataset"] != dataset or (row["method"], row["ablate"]) != expected
                        or "--timing-only" not in argv or "--phase-csv" in argv
                        or float(row["verify_s"]) != 0 or not isfinite(build_s)
                        or build_s <= 0 or rss_mib <= 0):
                    raise ValueError(f"{path}: invalid uninstrumented construction or RSS sample")
                rows.append({"dataset": dataset, "method": method, "replay": replay,
                             "build_s": build_s, "peak_process_rss_mib": rss_mib,
                             "source": str(path)})
    return rows


def resource_table(rows, output):
    tex = [
        r"% Generated by scripts/generate_resource_paper.py",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Initial maintenance construction and whole-process peak resident set size",
        r"(RSS) on the same three one-thread replays per method as the resident Star",
        r"comparison. Construction values are means and RSS values span the observed peaks.}",
        r"\label{tab:star-resident-resources}",
        r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lrrrr@{}}",
        r"\toprule",
        r"& \multicolumn{2}{c}{Construction (s)} & \multicolumn{2}{c}{Peak RSS (MiB)} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r"Graph & Regional & Star & Regional & Star \\",
        r"\midrule",
    ]
    for dataset in GENERATED:
        groups = [[row for row in rows if (row["dataset"], row["method"]) == (dataset, method)]
                  for method in METHODS]
        builds = [f"{mean(row['build_s'] for row in group):.3f}" for group in groups]
        ranges = []
        for group in groups:
            peaks = [row["peak_process_rss_mib"] for row in group]
            low, high = min(peaks), max(peaks)
            ranges.append(str(low) if low == high else f"{low}--{high}")
        tex.append(" & ".join([LABELS[dataset], *builds, *ranges]) + r" \\")
    tex.extend([r"\bottomrule", r"\end{tabular*}", r"\end{table}", ""])
    output.write_text("\n".join(tex))


def prefix_rows(replays):
    rows = []
    for replay in replays:
        path = Path(replay["source"])
        batches = path.with_name(path.name.replace(".runs.csv", ".batches.csv"))
        updates = (float(row["elapsed_us"]) / 1e6 for row in csv_rows(batches))
        for batch, maintenance_s in enumerate(accumulate(updates), 1):
            rows.append(dict(dataset=replay["dataset"], method=replay["method"],
                             replay=replay["replay"], batches=batch, build_s=replay["build_s"],
                             cumulative_maintenance_s=maintenance_s,
                             cumulative_latency_s=replay["build_s"] + maintenance_s,
                             construction_source=str(path), timing_source=str(batches)))
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, default=ROOT / ".build/vldb2027-star-resident")
    parser.add_argument("--paper", type=Path, default=ROOT / "VLDB2027_Work1-main/paper")
    args = parser.parse_args()
    try:
        rows = resource_rows(args.run.resolve(strict=True))
    except (KeyError, OSError, ValueError) as error:
        parser.error(str(error))
    tables = args.paper / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    write_csv(tables / "star_resident_resource_runs.csv", rows)
    write_csv(tables / "star_resident_prefix_times.csv", prefix_rows(rows))
    resource_table(rows, tables / "tab_star_resident_resources.tex")


if __name__ == "__main__":
    main()
