#!/usr/bin/env python3
"""Audit the archived paired replays and regenerate the main results table."""

import argparse
from math import isclose, isfinite
from pathlib import Path
from statistics import mean

from compare_replay import csv_rows
from experiment_replays import audit_paired_case
from revision_experiments import BUILD, ROOT, check_config, load_json
from run_temporal_windows import DAY, END, REVIEW_END, SCOPE, START, experiment_case, prepare


PHASE1 = BUILD / "vldb2027-revision-phase1"
LATENCY_ORDER = ("static", "msp", "full")
XEON = "Xeon Gold 6426Y"
QEMU = "QEMU"


def result(directory, name, counts, recordings, timings, mean_field):
    verified = csv_rows(directory / "full.verify.batches.csv")
    coverage = []
    for row in verified:
        region, edges = int(row["region_edges"]), int(row["final_m"])
        if not 0 <= region <= edges:
            raise ValueError(f"{directory}: invalid closure size in batch {row['batch']}")
        coverage.append(region / edges if edges else 0)

    latencies = {}
    for method, paths in timings.items():
        measured = [float(row["elapsed_us"]) / 1000
                    for path in paths for row in csv_rows(path)]
        if not all(isfinite(value) and value >= 0 for value in measured):
            raise ValueError(f"{directory}: invalid {method} latency")
        latency = mean(measured)
        if not latency > 0 or not isclose(latency, recordings[method], rel_tol=1e-10):
            raise ValueError(f"{directory}: {method} timing CSV disagrees with {mean_field}")
        latencies[method] = latency
    return (name, len(counts), sum(counts), mean(coverage), latencies)


def phase1(name, key, cpu_model, repeats):
    directory = PHASE1 / "main" / key
    spec = load_json(PHASE1 / "plan" / "main" / f"{key}.json")
    check_config(directory, spec)
    if (spec["threads"] != 1 or spec["runs"] != repeats or
            set(spec["methods"]) != set(LATENCY_ORDER) or
            cpu_model not in (directory / "hardware.txt").read_text().replace("(R)", "")):
        raise ValueError(f"{directory}: unexpected hardware or run protocol")
    recordings = {row["method"]: float(row["mean_ms"])
                  for row in csv_rows(directory / "summary.csv")}
    timings = {method: [directory / f"{method}.timing.batches.csv"] for method in LATENCY_ORDER}
    return result(directory, name, spec["counts"], recordings, timings, "summary.csv mean_ms")


def daily(name, run, key, start, end):
    directory = BUILD / run
    protocol = load_json(directory / "protocol.json")
    expected = dict(dataset_key=key, start_utc=start, end_utc=end, step_seconds=DAY,
                    window_days=[7], timing_replays=3, threads=1, cpu=0,
                    timer_scope=SCOPE, test_mode=False)
    if (any(protocol.get(field) != value for field, value in expected.items()) or
            "QEMU" not in protocol["machine"]["cpu_model"]):
        raise ValueError(f"{directory}: unexpected daily replay protocol")
    methods = protocol["methods"]
    source = prepare(directory, None, end, protocol)
    case, _, traces = experiment_case(source, 7, end, dataset=key, start=start, methods=methods)
    raw = directory / case["dataset"]
    audit_paired_case(raw, case, methods, 3, expected_traces=traces)
    means = {row["method"]: float(row["mean_ms_per_batch"])
             for row in csv_rows(directory / "summary.csv")
             if row["dataset"] == case["dataset"] and row["status"] == "verified"}
    timings = {method: [raw / f"{method}.timing.{trial}.batches.csv" for trial in range(3)]
               for method in ("static", "full")}
    return result(raw, name, case["batch_operations"], means, timings, "summary.csv mean_ms_per_batch")


def tex_row(workload):
    name, batches, events, coverage, means = workload
    cells = [name, f"{batches:,}", f"{events:,}", f"{coverage:.1%}".replace("%", r"\%")]
    best = min(means.values())
    for method in LATENCY_ORDER:
        if method == "full":
            cells.append(f"${means['static'] / means['full']:.2f}\\times$")
        value = means.get(method)
        cell = "---" if value is None else f"{value:.3f}"
        cells.append(rf"\textbf{{{cell}}}" if value == best else cell)
    return " & ".join(cells) + r" \\"


def gen_main(groups):
    lines = [
        "% Generated by scripts/generate_v5_coverage_tables.py",
        "% Sources: .build/vldb2027-revision-phase1/main/{email,wikivote,amazon,email-temporal,askubuntu}",
        "% and .build/vldb2027-{temporal-askubuntu-w7d-ablation,temporal-stackoverflow-fused,",
        "% stackoverflow-holdout-112d-b1d}. Means use *timing*.batches.csv (elapsed_us / 1000).",
        "% Coverage is the mean of region_edges / final_m from full.verify.batches.csv.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Single-thread mean latency (ms/batch) on eight complete",
        r"replays. Coverage averages the fraction of batch-end edges in the",
        r"Regional closure. Static/Regional divides the unrounded means.",
        r"Bold marks the lowest latency in each row. Dashes indicate unavailable MSP measurements.}",
        r"\label{tab:main-results}",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrrr@{}}",
        r"\toprule",
        r"Workload & Batches & Raw events & Coverage & Static & MSP & Static/Regional & Regional \\",
    ]
    for heading, workloads in groups:
        lines.extend((r"\midrule", rf"\multicolumn{{8}}{{@{{}}l}}{{\emph{{{heading}}}}} \\"))
        lines.extend(tex_row(workload) for workload in workloads)
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular*}", r"\end{table*}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper", type=Path, default=ROOT / "VLDB2027_Work1-main/paper")
    args = parser.parse_args()
    groups = [
        (f"Generated updates ({XEON} VM, five replays)", [
            phase1("Email (generated)", "email", XEON, 5),
            phase1("WikiVote", "wikivote", XEON, 5),
            phase1("Amazon", "amazon", XEON, 5),
        ]),
        (f"Transition-count batches, 7-day retention ({QEMU} VM, three replays)", [
            phase1("Email (interactions)", "email-temporal", QEMU, 3),
            phase1("Ask Ubuntu (target 1,000/batch)", "askubuntu", QEMU, 3),
        ]),
        (f"Daily timestamp checkpoints, 7-day retention ({QEMU} VM, three replays)", [
            daily("Ask Ubuntu (2015)", "vldb2027-temporal-askubuntu-w7d-ablation",
                  "askubuntu", START, END),
            daily("Stack Overflow (Jan. 1--28, 2015)", "vldb2027-temporal-stackoverflow-fused",
                  "stackoverflow", START, REVIEW_END),
            daily("Stack Overflow (112-day holdout)", "vldb2027-stackoverflow-holdout-112d-b1d",
                  "stackoverflow", REVIEW_END, REVIEW_END + 112 * DAY),
        ]),
    ]
    tables = args.paper / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    target = tables / "tab_main_results.tex"
    target.write_text(gen_main(groups))
    print(f"Audited eight coverage comparisons and wrote {target}")


if __name__ == "__main__":
    main()
