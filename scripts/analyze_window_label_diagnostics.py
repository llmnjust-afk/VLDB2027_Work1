#!/usr/bin/env python3
"""Audit label changes against the recorded daily Ask Ubuntu window timings."""

import argparse
import csv
from pathlib import Path
from statistics import correlation, mean, median
import subprocess
import tempfile

from analyze_label_changes import ARCHIVE_KEY, COUNTS, COUNTS_KEY, key
from compare_replay import csv_rows
from generate_temporal_windows_paper import paper_rows
from revision_experiments import ROOT
from revision_report import write_csv
from run_temporal_windows import METHODS


MEDIAN_COLUMNS = {method: f"{method.replace('-', '_')}_median_latency_ms" for method in METHODS}


def collect(formal, binary):
    """Replay for deterministic label counts and join to the recorded timing replays."""
    directory = Path(formal["source"])
    checkpoints = Path(formal["checkpoints"])
    input_dir = checkpoints.parent
    run = subprocess.run([binary, input_dir / "graph.txt", input_dir / "updates.stream"],
                         stdout=subprocess.PIPE, text=True, check=True)
    diagnostic = [{field: int(row[field]) for field in COUNTS}
                  for row in csv.DictReader(run.stdout.splitlines())]
    if not diagnostic:
        raise ValueError(f"{directory}: missing verification counts")
    verified = csv_rows(directory / "full.verify.batches.csv")
    timings = {
        method: [csv_rows(directory / f"{method}.timing.{i}.batches.csv")
                 for i in range(formal["replays"])]
        for method in METHODS
    }

    previous_m = diagnostic[0]["previous_m"]
    result = []
    batches = zip(diagnostic, verified, csv_rows(checkpoints), *timings["full"], strict=True)
    for index, (row, saved, checkpoint, *samples) in enumerate(batches):
        if (any(key(item, ARCHIVE_KEY) != key(row, COUNTS_KEY) for item in (saved, *samples)) or
                row["verify_ok"] != 1 or row["previous_m"] != previous_m or
                previous_m - row["net_deleted"] + row["net_inserted"] != row["final_m"] or
                row["region_edges"] - row["net_inserted"] != row["region_surviving"] or
                row["changed"] != row["promoted"] + row["demoted"] or
                not 0 <= row["changed_two_or_more"] <= row["changed"] <= row["region_surviving"] or
                not 0 <= row["region_triangles"] <= int(checkpoint["active_triangles"])):
            raise ValueError(f"{directory}: inconsistent diagnostic counts at batch {row['batch']}")
        previous_m = row["final_m"]
        medians = {
            column: median(float(replay[index]["elapsed_us"]) / 1000 for replay in timings[method])
            for method, column in MEDIAN_COLUMNS.items()
        }
        result.append(dict(window_days=formal["window_days"],
                           end_utc_inclusive=int(checkpoint["end_utc_inclusive"]), **row,
                           **medians,
                           source=str(directory)))
    return result


def summarize(window):
    times = [row["full_median_latency_ms"] for row in window]
    survivors = sum(row["region_surviving"] for row in window)
    changed = sum(row["changed"] for row in window)
    totals = {method: sum(row[column] for row in window)
              for method, column in MEDIAN_COLUMNS.items()}
    best_fixed = min(totals, key=totals.get)
    best_fixed_ms = totals[best_fixed]
    daily_best_ms = sum(min(row[column] for column in MEDIAN_COLUMNS.values()) for row in window)
    savings_ms = best_fixed_ms - daily_best_ms
    return dict(window_days=window[0]["window_days"], batches=len(window),
                mean_region_surviving=survivors / len(window), mean_changed=changed / len(window),
                pooled_changed_share=changed / survivors,
                mean_region_triangles=mean(row["region_triangles"] for row in window),
                mean_degree_sum=mean(row["degree_mass"] for row in window),
                edge_count_latency_corr=correlation([row["region_edges"] for row in window], times),
                degree_sum_latency_corr=correlation([row["degree_mass"] for row in window], times),
                best_fixed_method=best_fixed, best_fixed_total_ms=best_fixed_ms,
                hindsight_total_ms=daily_best_ms, hindsight_savings_fraction=savings_ms / best_fixed_ms,
                hindsight_savings_ms_per_day=savings_ms / len(window),
                source=window[0]["source"])


def table(rows):
    lines = [
        r"% Generated by scripts/analyze_window_label_diagnostics.py",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Label changes on surviving closure edges in Ask Ubuntu.",
        r"Surviving and relabeled counts are daily means. Share divides relabeled",
        r"counts by surviving closure visits, pooling all batches. $r_E$ and $r_D$",
        r"are Pearson correlations of closure size and endpoint degree sum with",
        r"Regional's daily median latency, respectively.}",
        r"\label{tab:window-label-diagnostics}",
        r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}rrrrrr@{}}",
        r"\toprule",
        r"Days & Surviving & Relabeled & Share & $r_E$ & $r_D$ " + r"\\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(
            f"{row['window_days']} & {row['mean_region_surviving']:,.0f} & {row['mean_changed']:,.0f} & "
            f"{row['pooled_changed_share']:.2%}".replace("%", r"\%") +
            f" & {row['edge_count_latency_corr']:.3f} & {row['degree_sum_latency_corr']:.3f} " + r"\\")
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular*}", r"\end{table}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, default=ROOT / ".build/vldb2027-temporal-windows")
    parser.add_argument("--paper", type=Path, default=ROOT / "VLDB2027_Work1-main/paper")
    args = parser.parse_args()
    try:
        formal = [row for row in paper_rows(args.run.resolve(strict=True)) if row["method"] == "full"]
        with tempfile.TemporaryDirectory(prefix="window-label-diagnostics.") as tmp:
            binary = Path(tmp) / "measure-label-changes"
            subprocess.run(["g++", "-std=c++17", "-O3", "-march=native", "-pthread",
                            f"-I{ROOT / 'src'}", str(ROOT / "scripts/measure_label_changes.cpp"),
                            "-o", str(binary)], check=True)
            paired = [collect(row, binary) for row in formal]
        summaries = [summarize(window) for window in paired]
        tables = args.paper / "tables"
        tables.mkdir(parents=True, exist_ok=True)
        write_csv(tables / "window_label_diagnostic_batches.csv",
                  [row for window in paired for row in window])
        write_csv(tables / "window_label_diagnostics.csv", summaries)
        (tables / "tab_window_label_diagnostics.tex").write_text(table(summaries))
        print(f"Verified {sum(map(len, paired))} diagnostic batches and exported {len(summaries)} windows")
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
