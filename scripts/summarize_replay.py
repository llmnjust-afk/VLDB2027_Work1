#!/usr/bin/env python3
"""Revalidate recorded replay results and emit a compact LaTeX latency table."""
import argparse
import json
from pathlib import Path

from compare_replay import check_rows, csv_rows


def verify(directory):
    if not (directory / "complete").is_file():
        raise ValueError(f"incomplete directory {directory}")
    metadata = json.loads((directory / "manifest.json").read_text())
    full = csv_rows(directory / "full.verify.batches.csv")
    counts = [int(row["raw_ops"]) for row in full]
    sizes = [int(row["final_m"]) for row in full]
    if len(counts) != metadata["batch_count"] or sum(counts) != metadata["operations"]:
        raise ValueError(f"batch totals disagree with manifest in {directory}")
    for method in metadata["methods"]:
        checked = csv_rows(directory / f"{method}.verify.batches.csv")
        timed = csv_rows(directory / f"{method}.timing.batches.csv")
        check_rows(checked, counts, 1, True)
        check_rows(timed, counts, metadata["runs"], False)
        if ([int(row["final_m"]) for row in checked] != sizes or
                [int(row["final_m"]) for row in timed] != sizes * metadata["runs"]):
            raise ValueError(f"checkpoint sizes disagree in {directory}: {method}")
    rows = csv_rows(directory / "summary.csv")
    if [row["method"] for row in rows] != metadata["methods"]:
        raise ValueError(f"summary methods disagree with manifest in {directory}")
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directories", nargs="+", type=Path)
    parser.add_argument("--latex", type=Path, required=True)
    args = parser.parse_args()
    columns = ["full", "nomerge", "peredge", "static", "msp"]
    lines = [r"% Generated by scripts/summarize_replay.py",
             r"\begin{tabular}{@{}lrrrrrr@{}}", r"\toprule",
             r"Graph & $T$ & Full & No-merge & PerEdge & Static & MSP \\",
             r"\midrule"]
    for directory in args.directories:
        rows = verify(directory)
        full = next(row for row in rows if row["method"] == "full")
        name = full["dataset"].replace("_", r"\_")
        values = {row["method"]: f"{float(row['mean_ms']):.3f}" for row in rows}
        lines.append(" & ".join([name, full["threads"]] +
                                [values.get(method, "--") for method in columns]) + r" \\")
        print(f"verified {directory}")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    args.latex.parent.mkdir(parents=True, exist_ok=True)
    args.latex.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
