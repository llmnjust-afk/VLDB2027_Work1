#!/usr/bin/env python3
"""Render the held-out comparison from verified traces and process measurements."""

import argparse
from math import isclose
from pathlib import Path

from compare_replay import csv_rows, digest
from revision_experiments import BUILD, ROOT, load_json
from run_unified_dynamic import METHODS, SCOPE, summarize


TABLE_METHODS = {
    "static": "Static",
    "static-net": "Static-Net",
    "full-fused": "Fused",
    "full-fused-pruned": "Fused-Pruned",
    "star-resident": "Resident Star",
    "luo-edge": "Luo-Edge",
}
CADENCES = {1: 168, 14: 12}
REPLAYS = 3
SECONDS_PER_DAY = 86_400
REPLAY_INTERVAL = (1_399_075_200, 1_413_590_400)
TOTAL_OPERATIONS = 5_085_642
METRICS = ("mean_ms_per_batch", "replay_mean_sd_ms", "pooled_p95_ms", "pooled_p99_ms",
           "mean_maintenance_s", "mean_build_s", "mean_build_plus_maintenance_s", "peak_process_rss_mib")


def load_table(results):
    plan = load_json(results / "protocol.json")
    methods = [*METHODS, "full-fused-pruned"]
    if (plan["timing_replays"] != REPLAYS or plan["threads"] != 1 or plan["smoke_only"]
            or plan["methods"] != methods or plan["timer_scope"] != SCOPE):
        raise ValueError("expected the formal pinned held-out comparison")
    cases = {case["dataset"]: case for case in plan["cases"]}
    stored = csv_rows(results / "summary.csv")
    summary = {(row["dataset"], row["method"]): row for row in stored}
    if len(cases) != len(CADENCES) or len(stored) != len(cases) * len(methods):
        raise ValueError("expected two complete cadences and one summary for each method")

    tables, input_ids = {}, set()
    for cadence, checkpoints in CADENCES.items():
        dataset = f"stackoverflow-2014-heldout-b{cadence}d"
        case = cases[dataset]
        operations = case["batch_operations"]
        seconds = cadence * SECONDS_PER_DAY
        if ((case["scope"], case["window_days"], case["checkpoint_seconds"]) != ("temporal", 7, seconds)
                or (case["start_utc"], case["end_utc"]) != REPLAY_INTERVAL
                or len(operations) != checkpoints or sum(operations) != TOTAL_OPERATIONS):
            raise ValueError(f"{dataset}: unexpected replay interval, cadence or input length")
        input_ids.add((case["graph_sha256"], case["raw_sha256"]))
        directory = results / dataset
        completion = load_json(directory / "complete.json")
        files = completion.pop("files")
        if completion != dict(case=case, methods=methods, replays=REPLAYS):
            raise ValueError(f"{dataset}: completion record differs from protocol")
        if files != {path.name: digest(path) for path in directory.glob("*.csv")}:
            raise ValueError(f"{dataset}: replay files differ from completion hashes")

        recomputed, _, _ = summarize(directory, case, methods, REPLAYS, None, False)
        tables[cadence] = {}
        for actual in recomputed:
            method = actual["method"]
            expected = summary[dataset, method]
            if ((expected["status"], expected["verified_batches"], expected["timing_replays"]) !=
                    ("verified", str(checkpoints), str(REPLAYS))
                    or any(not isclose(actual[field], float(expected[field]), rel_tol=1e-10, abs_tol=1e-10)
                           for field in METRICS)):
                raise ValueError(f"{dataset}/{method}: summary disagrees with replay measurements")
            tables[cadence][method] = actual
    if len(input_ids) != 1:
        raise ValueError("cadences use different starting graphs or source streams")
    return tables


def render(tables):
    best = {cadence: min(rows, key=lambda method: rows[method]["mean_ms_per_batch"])
            for cadence, rows in tables.items()}
    lines = [
        "% Generated by scripts/generate_main4_heldout_paper.py",
        r"\centering",
        r"\caption{2014 held-out Stack Overflow. Mean and pooled P95",
        r"are in ms per checkpoint. RSS is peak MiB across three timing replays.",
        r"Bold marks the lowest mean.}",
        r"\label{tab:main4-heldout}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{1.5pt}",
        r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lrrrrrr@{}}",
        r"\toprule",
        rf" & \multicolumn{{3}}{{c}}{{Daily ({CADENCES[1]} batches)}} & "
        rf"\multicolumn{{3}}{{c}}{{14-day ({CADENCES[14]} batches)}} \\",
        r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
        r"Method & Mean & P95 & RSS & Mean & P95 & RSS \\",
        r"\midrule",
    ]
    for method, label in TABLE_METHODS.items():
        cells = [label]
        for cadence in CADENCES:
            row = tables[cadence][method]
            avg = f"{row['mean_ms_per_batch']:.2f}"
            if method == best[cadence]:
                avg = rf"\textbf{{{avg}}}"
            cells.extend([avg, f"{row['pooled_p95_ms']:.2f}", str(row["peak_process_rss_mib"])])
        lines.append(" & ".join(cells) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular*}"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=BUILD / "vldb2027-main4-heldout")
    parser.add_argument("--output", type=Path,
                        default=ROOT / "VLDB2027_Work1-main/paper/tables/tab_main4_heldout.tex")
    args = parser.parse_args()
    args.output.write_text(render(load_table(args.results)))


if __name__ == "__main__":
    main()
