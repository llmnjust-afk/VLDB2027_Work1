#!/usr/bin/env python3
"""Summarize verified Star runs with their own kernel and wrapper boundaries."""
import argparse
import json
from pathlib import Path
from statistics import mean

from compare_replay import check_rows, csv_rows
from summarize_replay import verify


def write_table(pairs, output):
    lines = [r"% Generated by scripts/summarize_star.py",
             r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
             r"Graph & Full & Star kernel & Star wall \\", r"\midrule"]
    for native, star in pairs:
        native_rows = verify(native)
        native_meta = json.loads((native / "manifest.json").read_text())
        star_meta = json.loads((star / "manifest.json").read_text())
        if not (star / "complete").is_file():
            raise ValueError(f"incomplete Star run: {star}")
        if list(native_meta["inputs"].values())[:2] != list(star_meta["inputs"].values())[:2]:
            raise ValueError(f"graph or stream digests disagree: {native}, {star}")
        full = csv_rows(native / "full.verify.batches.csv")
        counts = [int(row["raw_ops"]) for row in full]
        sizes = [int(row["final_m"]) for row in full]
        verified = csv_rows(star / "star.verify.batches.csv")
        timed = csv_rows(star / "star.timing.batches.csv")
        runs = star_meta["runs"]
        check_rows(verified, counts, 1, True)
        check_rows(timed, counts, runs, False)
        if [int(row["final_m"]) for row in verified] != sizes:
            raise ValueError(f"Star checkpoint sizes disagree: {star}")
        if [int(row["final_m"]) for row in timed] != sizes * runs:
            raise ValueError(f"Star timing replay sizes disagree: {star}")
        full_summary = next(row for row in native_rows if row["method"] == "full")
        if full_summary["threads"] != str(star_meta["threads"]):
            raise ValueError("Star table needs matched nominal thread settings")
        name = full_summary["dataset"].replace("_", r"\_")
        values = (float(full_summary["mean_ms"]), mean(float(row["kernel_ms"]) for row in timed),
                  mean(float(row["elapsed_ms"]) for row in timed))
        lines.append(" & ".join([name, *(f"{value:.3f}" for value in values)]) + r" \\")
        print(f"verified {native} against {star}")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    output.write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pair", nargs=2, type=Path, action="append", required=True,
                        metavar=("NATIVE_DIR", "STAR_DIR"))
    parser.add_argument("--latex", type=Path, required=True)
    args = parser.parse_args()
    write_table(args.pair, args.latex)


if __name__ == "__main__":
    main()
