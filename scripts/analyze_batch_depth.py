#!/usr/bin/env python3
"""Summarize event reduction and label depth from the audited main replays."""

import argparse
from pathlib import Path

from analyze_label_changes import (
    ARCHIVE_KEY, COUNTS_KEY, DATASETS, check_inputs_unchanged, key, workload_map,
)
from compare_replay import csv_rows
from revision_experiments import ROOT
from revision_report import LABELS, write_csv


def summarize(dataset, archive, spec, counts):
    check_inputs_unchanged(spec)
    static_path = archive / "static.verify.batches.csv"
    full_path = archive / "full.verify.batches.csv"
    labels_path = counts / f"{dataset}.csv"
    static, full, labels = (csv_rows(path) for path in (static_path, full_path, labels_path))
    if not len(static) == len(full) == len(labels) == len(spec["counts"]) > 0:
        raise ValueError(f"{dataset}: mismatched checkpoint counts")

    raw_events = ordered_mutations = net_mutations = multilevel_batches = 0
    cancellation_batches = mixed_update_batches = mixed_label_batches = 0
    peak_cancelled_share = 0
    last_final = int(labels[0]["previous_m"])
    for batch, (ordered, net, label, declared) in enumerate(
        zip(static, full, labels, spec["counts"]), start=1
    ):
        raw = int(ordered["raw_ops"])
        ordered_deleted, ordered_inserted = key(ordered, ("deleted", "inserted"))
        net_deleted, net_inserted = key(net, ("deleted", "inserted"))
        ordered_count = ordered_deleted + ordered_inserted
        net_count = net_deleted + net_inserted
        previous, final = key(label, ("previous_m", "final_m"))
        changed, deep, promoted, demoted = key(
            label, ("changed", "changed_two_or_more", "promoted", "demoted")
        )
        if (
            key(ordered, ("batch", "raw_ops", "final_m")) != (batch, declared, final)
            or key(net, ("batch", "raw_ops", "final_m")) != (batch, declared, final)
            or key(net, ARCHIVE_KEY) != key(label, COUNTS_KEY)
            or any(row["verify_ok"] != "1" for row in (ordered, net, label))
            or previous != last_final
            or previous - net_deleted + net_inserted != final
            or not 0 <= net_count <= ordered_count <= raw
            or not 0 <= net_deleted <= ordered_deleted
            or ordered_deleted - net_deleted != ordered_inserted - net_inserted
            or not 0 <= deep <= changed <= int(label["region_surviving"])
            or min(promoted, demoted) < 0
            or promoted + demoted != changed
        ):
            raise ValueError(f"{dataset}: inconsistent counts at batch {batch}")
        raw_events += raw
        ordered_mutations += ordered_count
        net_mutations += net_count
        cancelled = ordered_count - net_count
        cancellation_batches += cancelled > 0
        peak_cancelled_share = max(peak_cancelled_share, cancelled / raw if raw else 0)
        multilevel_batches += deep > 0
        mixed_update_batches += net_deleted > 0 and net_inserted > 0
        mixed_label_batches += promoted > 0 and demoted > 0
        last_final = final

    if raw_events == 0:
        raise ValueError(f"{dataset}: no events across verified checkpoints")
    return dict(
        dataset=dataset,
        batches=len(labels),
        raw_events=raw_events,
        ordered_mutations=ordered_mutations,
        net_mutations=net_mutations,
        noop_events=raw_events - ordered_mutations,
        cancelled_mutations=ordered_mutations - net_mutations,
        noop_percent=100 * (raw_events - ordered_mutations) / raw_events,
        cancelled_percent=100 * (ordered_mutations - net_mutations) / raw_events,
        cancellation_batches=cancellation_batches,
        peak_cancelled_percent=100 * peak_cancelled_share,
        multilevel_batches=multilevel_batches,
        mixed_update_batches=mixed_update_batches,
        mixed_label_batches=mixed_label_batches,
        initial_graph_sha256=spec["inputs"][0],
        ordered_stream_sha256=spec["inputs"][1],
        static_verification_source=str(static_path),
        full_verification_source=str(full_path),
        label_verification_source=str(labels_path),
    )


def write_table(rows, path):
    lines = [
        r"% Generated by scripts/analyze_batch_depth.py",
        r"\begin{table}[!tb]",
        r"\centering",
        r"\caption{Batch reduction and trussness changes on the complete",
        r"main streams. No-op and cancelled events are percentages of all",
        r"raw requests. The last column counts batches with at least one",
        r"surviving edge whose trussness changes by two or more levels.}",
        r"\label{tab:batch-depth-evidence}",
        r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lrrr@{}}",
        r"\toprule",
        r"Workload & No-op & Cancelled & $|\Delta\tau|\ge 2$ \\",
        r"\midrule",
        r"\multicolumn{4}{@{}l}{\emph{Generated updates}} \\",
    ]
    for row in rows:
        dataset = row["dataset"]
        if dataset == "email-temporal":
            lines.extend((
                r"\midrule",
                r"\multicolumn{4}{@{}l}{\emph{Timestamp-driven replay}} \\",
            ))
        lines.append(
            f"{LABELS[dataset]} & {row['noop_percent']:.2f}\\% & "
            f"{row['cancelled_percent']:.2f}\\% & "
            f"{row['multilevel_batches']}/{row['batches']} " + r"\\"
        )
    lines.extend((r"\bottomrule", r"\end{tabular*}", r"\end{table}"))
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, default=ROOT / ".build/vldb2027-revision-phase1")
    parser.add_argument("--counts", type=Path, default=ROOT / ".build/vldb2027-label-changes")
    parser.add_argument("--paper", type=Path, default=ROOT / "VLDB2027_Work1-main/paper")
    args = parser.parse_args()
    try:
        workloads = workload_map(args.run.resolve(strict=True))
        counts = args.counts.resolve(strict=True)
        rows = [summarize(dataset, *workloads[dataset], counts) for dataset in DATASETS]
        output = args.paper / "tables"
        output.mkdir(parents=True, exist_ok=True)
        write_csv(output / "batch_depth_evidence.csv", rows)
        write_table(rows, output / "tab_batch_depth_evidence.tex")
    except (OSError, ValueError, KeyError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
